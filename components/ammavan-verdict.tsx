"use client";

import { useEffect, useRef, useState } from "react";
import { LoaderCircle, RefreshCw, Sparkles, Volume2, WifiOff } from "lucide-react";
import type { AmmavanErrorCode, AmmavanResponse, Language } from "@/lib/types";
import { AmmavanAvatar } from "./ammavan-avatar";

const MESSAGES: Record<AmmavanErrorCode, string> = {
  not_configured: "No Sarvam API key is configured on the server (SARVAM_API_KEY), so this is an offline verdict.",
  invalid_key: "Sarvam rejected the API key (HTTP 403). Check SARVAM_API_KEY in .env.local, then restart the server.",
  rate_limited: "Sarvam is rate-limiting requests right now. Wait a moment and retry.",
  timeout: "Sarvam took too long to answer. Retry in a moment.",
  network: "Couldn't reach Sarvam. Check your connection and retry.",
  server_error: "Sarvam had a server problem. Retry in a moment.",
  bad_response: "Sarvam sent back something Ammavan couldn't read. Retry, or the offline verdict below is still valid.",
};

const VOICE_LABEL: Record<Language, string> = {
  ml: "Ammavan speaks",
  en: "Let Ammavan speak",
  ta: "Ammavan பேசட்டும்",
  hi: "अम्मावन को बोलने दें",
};

export function AmmavanVerdict({
  data,
  loading,
  language,
  onRetry,
}: {
  data: AmmavanResponse | null;
  loading: boolean;
  language: Language;
  onRetry?: () => void;
}) {
  const mood = data?.mood ?? "amused";
  const audioRef = useRef<HTMLAudioElement>(null);
  const [speakingLoading, setSpeakingLoading] = useState(false);
  const [audio, setAudio] = useState<{ url: string; key: string } | null>(null);
  const currentAudioKey = `${data?.headline ?? ""}|${data?.verdict ?? ""}|${language}`;
  const [voiceError, setVoiceError] = useState<string | null>(null);

  useEffect(() => {
    return () => {
      if (audio?.url) URL.revokeObjectURL(audio.url);
    };
  }, [audio]);

  async function speakVerdict() {
    if (!data || speakingLoading) return;
    setSpeakingLoading(true);
    setVoiceError(null);
    try {
      const text = `${data.headline}. ${data.verdict}${data.rescueAdvice ? `. ${data.rescueAdvice}` : ""}`.trim();
      const response = await fetch("/api/ammavan/speak", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text, language }),
      });
      if (!response.ok) {
        const details: { error?: string } = await response.json().catch(() => ({}));
        throw new Error(details.error || "Ammavan's voice could not be generated. Please try again.");
      }
      const blob = await response.blob();
      if (!blob.size) throw new Error("The speech service returned empty audio. Please try again.");
      const nextUrl = URL.createObjectURL(blob);
      setAudio((oldAudio) => {
        if (oldAudio?.url) URL.revokeObjectURL(oldAudio.url);
        return { url: nextUrl, key: currentAudioKey };
      });
      // Playback is initiated by the user's button click, so browser autoplay policies are respected.
      window.setTimeout(() => {
        void audioRef.current?.play().catch(() => {
          setVoiceError("Audio is ready, but playback was blocked. Press Play in the audio controls.");
        });
      }, 0);
    } catch (error) {
      setVoiceError(error instanceof Error ? error.message : "Couldn't generate Ammavan's voice. Please retry.");
    } finally {
      setSpeakingLoading(false);
    }
  }

  return (
    <section className="card border-brand/20 bg-gradient-to-br from-white to-brand-soft/60 p-5" aria-live="polite" aria-busy={loading || !data}>
      <div className="flex flex-wrap items-center gap-2">
        <h2 className="text-lg font-bold">AI Ammavan&apos;s Verdict</h2>
        {data && (
          <span className={`ml-auto flex items-center gap-1 rounded-full px-2 py-1 text-[11px] font-semibold ${data.source === "sarvam" ? "bg-emerald-50 text-emerald-700" : "bg-amber-50 text-amber-700"}`}>
            {data.source === "sarvam" ? <><Sparkles size={12} aria-hidden /> Generated by Sarvam AI</> : <><WifiOff size={12} aria-hidden /> Offline verdict</>}
          </span>
        )}
      </div>

      <div className="mt-4 flex flex-col items-start gap-4 sm:flex-row">
        <div className="shrink-0 self-center sm:self-start"><AmmavanAvatar mood={loading || !data ? "amused" : mood} size={104} thinking={loading || !data || speakingLoading} /></div>

        {loading || !data ? (
          <div className="bubble w-full rounded-2xl border border-line bg-white p-4" role="status" aria-label="Ammavan is reading your plan">
            <p className="text-sm font-semibold text-navy">Ammavan is reading your plan<span className="dots" aria-hidden="true"><span>.</span><span>.</span><span>.</span></span></p>
            <div className="mt-3 space-y-2"><div className="skeleton h-4 w-11/12" /><div className="skeleton h-4 w-9/12" /><div className="skeleton h-4 w-10/12" /></div>
          </div>
        ) : (
          <div className="bubble bubble-in w-full rounded-2xl border border-line bg-white p-4">
            <p className="text-lg font-extrabold leading-snug text-brand">{data.headline}</p>
            <p className="mt-2 whitespace-pre-line text-[15px] leading-relaxed text-navy">{data.verdict}</p>
            {data.rescueAdvice && <p className="mt-3 rounded-lg bg-red-50 p-3 text-sm text-red-800">🚨 {data.rescueAdvice}</p>}
          </div>
        )}
      </div>

      {data && !loading && (
        <div className="mt-4 rounded-xl border border-brand/15 bg-white/80 p-3">
          <button type="button" onClick={() => void speakVerdict()} disabled={speakingLoading} className="btn-primary inline-flex items-center gap-2 disabled:cursor-not-allowed disabled:opacity-60">
            {speakingLoading ? <LoaderCircle className="animate-spin" size={17} aria-hidden /> : <Volume2 size={17} aria-hidden />}
            {speakingLoading ? "Ammavan is preparing his voice…" : VOICE_LABEL[language]}
          </button>
          <p className="mt-2 text-xs text-ink">Hear Ammavan&apos;s verdict aloud. Audio is generated when you press the button.</p>
          {voiceError && <p role="alert" className="mt-2 text-sm font-medium text-red-700">{voiceError}</p>}
          {audio?.key === currentAudioKey && (
            <audio ref={audioRef} className="mt-3 block w-full" controls preload="metadata" src={audio.url}>
              Your browser does not support audio playback.
            </audio>
          )}
        </div>
      )}

      {data && data.source === "fallback" && data.reason && (
        <div role="alert" className="mt-4 flex flex-col gap-2 rounded-lg bg-amber-50 p-3 text-sm text-amber-900 sm:flex-row sm:items-center sm:justify-between">
          <span>{MESSAGES[data.reason]} Your score and breakdown are unaffected.</span>
          {onRetry && <button onClick={onRetry} className="btn-ghost shrink-0 !py-1.5 text-xs"><RefreshCw size={14} aria-hidden /> Retry Ammavan</button>}
        </div>
      )}
      {data && data.source === "sarvam" && onRetry && (
        <button onClick={onRetry} className="mt-3 inline-flex items-center gap-1 text-xs font-semibold text-brand hover:underline"><RefreshCw size={12} aria-hidden /> Ask Ammavan again for a fresh roast</button>
      )}
      <p className="mt-3 text-[11px] text-ink">Ammavan gives general suggestions, not verified facts about prices, hours, weather or availability. The score is a heuristic estimate of planning risk, not a validated probability of regret.</p>
    </section>
  );
}
