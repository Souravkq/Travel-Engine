"use client";
import { useEffect, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { AlertTriangle, ArrowRight, LifeBuoy } from "lucide-react";
import { AlternativeComparison } from "@/components/alternative-comparison";
import { LocalDiscovery } from "@/components/local-discovery";
import { NoTrip } from "@/components/no-trip";
import type { Plan } from "@/lib/alternatives";
import { useTrip } from "@/lib/trip-storage";
import type { ScoreResult } from "@/lib/types";
import { coreKey } from "@/lib/use-analysis";

type Data = { current: ScoreResult; plans: Plan[]; rescue: boolean; recommendedId: Plan["id"]; ammavan: { comment: string; source: "sarvam" | "fallback" } };

export default function AlternativesPage() {
  const router = useRouter();
  const { trip, loaded, setTrip } = useTrip();
  const [data, setData] = useState<Data | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [selected, setSelected] = useState<Plan["id"] | null>(null);
  const key = coreKey(trip);

  useEffect(() => {
    if (!key) return;
    let off = false;
    setData(null); setError(null); // eslint-disable-line react-hooks/set-state-in-effect
    fetch("/api/alternatives", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ trip: JSON.parse(key) }) })
      .then((r) => r.json())
      .then((d) => {
        if (off) return;
        if (!d.ok) throw new Error(Object.values(d.errors ?? {})[0] as string);
        setData(d); setSelected(d.recommendedId);
      })
      .catch((e: Error) => !off && setError(e.message || "Couldn't build alternatives."));
    return () => { off = true; };
  }, [key]);

  if (!loaded) return null;
  if (!trip) return <NoTrip />;

  const plan = data?.plans.find((p) => p.id === selected);

  function apply() {
    if (!plan || !trip) return;
    setTrip({ ...plan.trip, companionPrefs: trip.companionPrefs }); // updates the saved trip
    sessionStorage.setItem("tre:applied", "1");
    router.push("/results"); // results page re-analyses the revised plan
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-3xl font-bold">{data?.rescue ? "Rescue Mode: Try These Plan Adjustments" : "Try These Plan Adjustments"}</h1>
        <p className="mt-1 text-sm">See how small changes can reduce your regret risk. Every score below is recalculated by the same scoring engine.</p>
      </div>

      {data?.rescue && (
        <div className="flex gap-2 rounded-2xl border border-red-200 bg-red-50 p-4 text-sm font-semibold text-red-900"><LifeBuoy size={18} className="mt-0.5 shrink-0" aria-hidden /> Your current plan is high risk ({data.current.score}/100). We&apos;ve highlighted the lowest-risk option for you.</div>
      )}
      {error && <p role="alert" className="flex gap-2 rounded-lg bg-red-50 p-3 text-sm text-red-800"><AlertTriangle size={16} aria-hidden />{error}</p>}
      {!data && !error && <div className="space-y-3" role="status" aria-label="Building alternative plans"><div className="skeleton h-12" /><div className="skeleton h-80" /></div>}

      {data && plan && (
        <>
          <div role="tablist" aria-label="Plan strategies" className="grid gap-3 sm:grid-cols-3">
            {data.plans.map((p) => (
              <button key={p.id} role="tab" aria-selected={selected === p.id} onClick={() => setSelected(p.id)}
                className={`card p-4 text-left transition ${selected === p.id ? "!border-brand ring-2 ring-brand/30" : "hover:bg-lavender"}`}>
                <div className="flex items-center justify-between gap-2"><span className="font-bold text-navy">{p.name}</span>{data.recommendedId === p.id && <span className="chip">Recommended</span>}</div>
                <p className="mt-1 text-xs">{p.tagline}</p>
                <p className="mt-2 text-sm font-semibold text-navy">{data.current.score} → {p.result.score} <span className="text-xs font-normal">({p.result.level})</span></p>
              </button>
            ))}
          </div>

          <AlternativeComparison current={data.current} currentTrip={trip} plan={plan} />

          <section className="card border-brand/20 bg-gradient-to-br from-white to-brand-soft/50 p-5">
            <h2 className="font-bold">☕ Ammavan on these changes</h2>
            <p className="mt-2 text-sm text-navy">{data.ammavan.comment}</p>
            <p className="mt-2 text-[11px]">{data.ammavan.source === "sarvam" ? "Generated by Sarvam AI. " : "Offline comment (Sarvam unavailable). "}General suggestions only.</p>
          </section>

          <div className="flex flex-wrap items-center gap-3">
            <button className="btn-primary" onClick={apply}>Apply These Changes to My Plan <ArrowRight size={16} aria-hidden /></button>
            <Link href="/results" className="btn-ghost">Back to Results</Link>
            <Link href="/trip" className="btn-ghost">Edit Trip</Link>
          </div>
          <p className="text-xs">Applying overwrites your saved plan with the selected plan&apos;s values and re-analyses it. You can edit anything afterwards.</p>

          <LocalDiscovery trip={plan.trip} />
        </>
      )}
    </div>
  );
}
